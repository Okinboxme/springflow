    // ================================================================

    private void planJavaEndpoint(
            ModelDefinition model,
            String modelPackage,
            String modelPackageName)
            throws IOException {

        FieldDefinition idField = model.idField();
        String idType = idField != null
                ? idField.getType()
                : "Long";

        StringBuilder sb =
                new StringBuilder();

        sb.append("package ")
                .append(modelPackageName)
                .append(";\n\n");

        sb.append("/* Generated by SpringFlow. "
                + "DO NOT EDIT. */\n\n");

        sb.append("import dev.springflow.core.annotation.Endpoint;\n");
        sb.append("import dev.springflow.core.annotation.EndpointMethod;\n\n");

        sb.append("import java.util.ArrayList;\n");
        sb.append("import java.util.List;\n");
        sb.append("import java.util.concurrent.atomic.AtomicLong;\n\n");

        sb.append("@Endpoint\n");
        sb.append("public class ")
                .append(model.endpointName())
                .append(" {\n\n");

        sb.append("    private final List<")
                .append(model.getName())
                .append("> ")
                .append(model.pluralVarName())
                .append(" = new ArrayList<>();\n\n");

        sb.append("    private final AtomicLong idGenerator = new AtomicLong(1);\n\n");

        // findAll
        sb.append("    @EndpointMethod\n");
        sb.append("    public List<")
                .append(model.getName())
                .append("> findAll() {\n");
        sb.append("        return new ArrayList<>(")
                .append(model.pluralVarName())
                .append(");\n");
        sb.append("    }\n\n");

        // findById
        sb.append("    @EndpointMethod\n");
        sb.append("    public ")
                .append(model.getName())
                .append(" findById(")
                .append(idType)
                .append(" id) {\n");
        sb.append("        return ")
                .append(model.pluralVarName())
                .append(".stream()\n");
        sb.append("                .filter(item -> item.getId().equals(id))\n");
        sb.append("                .findFirst()\n");
        sb.append("                .orElse(null);\n");
        sb.append("    }\n\n");

        // create
        sb.append("    @EndpointMethod\n");
        sb.append("    public ")
                .append(model.getName())
                .append(" create(\n");

        List<FieldDefinition> createFields =
                model.createFields();

        for (int i = 0; i < createFields.size(); i++) {

            sb.append("            ");
            sb.append(createFields.get(i).getType());
            sb.append(" ");
            sb.append(createFields.get(i).getName());

            if (i < createFields.size() - 1) {
                sb.append(",");
            }

            sb.append("\n");
        }

        sb.append("    ) {\n");
        sb.append("        ")
                .append(model.getName())
                .append(" item = new ")
                .append(model.getName())
                .append("(\n");
        sb.append("                idGenerator.getAndIncrement(),\n");

        // All non-id fields in order; use defaults for
        // fields not in createFields
        List<FieldDefinition> nonIdFields =
                model.nonIdFields();

        for (int i = 0; i < nonIdFields.size(); i++) {

            FieldDefinition field = nonIdFields.get(i);

            sb.append("                ");

            if (createFields.contains(field)) {
                sb.append(field.getName());
            } else if (field.getDefaultValue() != null) {
                sb.append(field.getDefaultValue());
            } else if (field.isString()) {
                sb.append("null");
            } else if (field.isNumeric()) {
                sb.append("0");
            } else if (field.isBoolean()) {
                sb.append("false");
            } else {
                sb.append("null");
            }

            if (i < nonIdFields.size() - 1) {
                sb.append(",");
            }

            sb.append("\n");
        }

        sb.append("        );\n\n");

        sb.append("\n        ")
                .append(model.pluralVarName())
                .append(".add(item);\n");
        sb.append("        return item;\n");
        sb.append("    }\n\n");

        // update
        sb.append("    @EndpointMethod\n");
        sb.append("    public ")
                .append(model.getName())
                .append(" update(\n");

        List<FieldDefinition> updateFields =
                model.nonIdFields();

        sb.append("            ");
        sb.append(idType);
        sb.append(" id,\n");

        for (int i = 0; i < updateFields.size(); i++) {

            sb.append("            ");
            sb.append(updateFields.get(i).getType());
            sb.append(" ");
            sb.append(updateFields.get(i).getName());

            if (i < updateFields.size() - 1) {
                sb.append(",");
            }

            sb.append("\n");
        }

        sb.append("    ) {\n");
        sb.append("        ")
                .append(model.getName())
                .append(" item = findById(id);\n\n");

        sb.append("        if (item == null) {\n");
        sb.append("            return null;\n");
        sb.append("        }\n\n");

        for (FieldDefinition field : updateFields) {

            sb.append("        item.set")
                    .append(capitalize(field.getName()))
                    .append("(")
                    .append(field.getName())
                    .append(");\n");
        }

        sb.append("\n        return item;\n");
        sb.append("    }\n\n");

        // delete
        sb.append("    @EndpointMethod\n");
        sb.append("    public boolean delete(")
                .append(idType)
                .append(" id) {\n");

        sb.append("        return ")
                .append(model.pluralVarName())
                .append(".removeIf(\n");
        sb.append("                item -> item.getId().equals(id)\n");
        sb.append("        );\n");
        sb.append("    }\n");

        sb.append("}\n");

        addPlanned(
                "src/main/java/"
                        + modelPackage + "/"
                        + model.endpointName() + ".java",
                sb.toString()
        );
    }

