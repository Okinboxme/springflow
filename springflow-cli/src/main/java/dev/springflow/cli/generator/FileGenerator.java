    private void addPlanned(
            String relativePath,
            String content) {

        planned.add(new PlannedFile(
                relativePath,
                content
        ));
    }

    private void execute() throws IOException {

        for (PlannedFile file : planned) {

            Path path =
                    projectRoot.resolve(file.relativePath);

            boolean written =
                    BackupManager.writeWithBackup(
                            path,
                            file.content,
                            backupEnabled
                    );

            if (written) {

                System.out.println(
                        "  + " + file.relativePath
                );

            } else {

                System.out.println(
                        "  ~ " + file.relativePath
                        + " (skipped, not generated)"
                );
            }
        }
    }

    /**
     * Detect the Java package name from the existing
     * Application.java file.
     */
    private String detectPackage() {

        Path srcDir =
                projectRoot.resolve("src/main/java");

        if (!Files.isDirectory(srcDir)) {
            return "com.example.app";
        }

        try {

            return Files.walk(srcDir)
                    .filter(p -> p.getFileName()
                            .toString()
                            .equals("Application.java"))
                    .findFirst()
                    .map(p -> {
                        try {
                            String content =
                                    Files.readString(p);

                            int pkgStart =
                                    content.indexOf("package ");

                            if (pkgStart < 0) {
                                return "com.example.app";
                            }

                            int pkgEnd =
                                    content.indexOf(
                                            ';',
                                            pkgStart
                                    );

                            if (pkgEnd < 0) {
                                return "com.example.app";
                            }

                            return content
                                    .substring(
                                            pkgStart + 8,
                                            pkgEnd
                                    )
                                    .trim();

                        } catch (IOException e) {
                            return "com.example.app";
                        }
                    })
                    .orElse("com.example.app");

        } catch (IOException e) {
            return "com.example.app";
        }
    }

    private static String capitalize(String name) {

        if (name == null || name.isEmpty()) {
            return name;
        }

        return Character.toUpperCase(name.charAt(0))
                + name.substring(1);
    }

